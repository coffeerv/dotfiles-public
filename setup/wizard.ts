const MISE_TOOLS = ["chezmoi", "age", "fnox", "gh"];

function checkPrereqs(pm: Data["password_manager"]) {
  title("Checking your tools");
  const missing = MISE_TOOLS.filter((t) => !has(t === "age" ? "age-keygen" : t));
  if (!has("git")) abort("git is not installed. Install it first: https://git-scm.com/downloads");
  if (missing.length) {
    const pkgs = missing.map((t) => (t === "gh" ? "github-cli" : t));
    say(`Missing: ${missing.join(", ")}. They can be installed with mise: mise use -g ${pkgs.join(" ")}`);
    if (confirm("Install them now?")) {
      if (!run(["mise", "use", "-g", ...pkgs]).ok) abort("mise couldn't install them; fix that and run the wizard again.");
      say("Installed. If a tool still isn't found, open a new terminal and run the wizard again.");
    }
  }
  const cli = pm === "bitwarden" ? "bw" : "op";
  if (!has(cli)) {
    say(
      pm === "bitwarden"
        ? "The Bitwarden CLI (bw) isn't installed: https://bitwarden.com/help/cli/  (you can continue; it's needed for secrets-sync)"
        : "The 1Password CLI (op) isn't installed: https://developer.1password.com/docs/cli/get-started/  (you can continue, but key creation will be manual)",
    );
  }
  say("Done.");
}

function ensureAgeKey() {
  const k = join(homedir(), ".config", "fnox", "age.txt");
  if (existsSync(k)) return;
  if (!has("age-keygen")) abort("age-keygen is missing: mise use -g age");
  mkdirSync(dirname(k), { recursive: true });
  if (!run(["age-keygen", "-o", k], { quiet: true }).ok) abort(`Couldn't create ${k}`);
  say(`Created this machine's encryption key for the local secrets cache: ${k} (never commit it).`);
}

function opEnsureVault(vault: string): boolean {
  if (run(["op", "vault", "get", vault], { quiet: true }).ok) return true;
  if (!confirm(`These keys will be stored in a 1Password vault called "${vault}", which doesn't exist yet. Create it?`)) return false;
  return run(["op", "vault", "create", vault], { quiet: true }).ok;
}

function opCreateKey(vault: string, itemTitle: string): string | null {
  if (!opEnsureVault(vault)) return null;
  // Reuse a key this wizard created on an earlier (maybe cancelled) run instead of making a duplicate.
  const prev = run(["op", "item", "get", itemTitle, "--vault", vault, "--format", "json"], { quiet: true });
  if (prev.ok) {
    const r = run(["op", "read", `op://${vault}/${JSON.parse(prev.out).id}/public key`], { quiet: true });
    if (r.ok) { say(`  Found "${itemTitle}" from an earlier run; reusing it.`); return r.out; }
  }
  const c = run(["op", "item", "create", "--category", "SSH Key", "--title", itemTitle, "--vault", vault, "--ssh-generate-key", "ed25519", "--format", "json"], { quiet: true });
  if (!c.ok) { say(`  1Password said: ${c.err}`); return null; }
  const id = JSON.parse(c.out).id as string;
  const r = run(["op", "read", `op://${vault}/${id}/public key`], { quiet: true });
  return r.ok ? r.out : null;
}

function askKey(d: Data, i: Identity, h: Host, current?: string): string {
  const what = `${i.label} on ${h.host}`;
  const keep = current && !isPlaceholder(current);
  type K = "keep" | "create" | "paste" | "skip";
  const opts: { value: K; label: string }[] = [];
  if (keep) opts.push({ value: "keep", label: `Keep the current key (${current!.slice(0, 32)}…)` });
  if (d.password_manager === "1password" && has("op")) opts.push({ value: "create", label: `Create a new key in 1Password (vault "${i.vault}")` });
  opts.push({ value: "paste", label: "Paste a public key I already have" });
  opts.push({ value: "skip", label: "Skip for now (you can't push or sign as this account until you add a key)" });
  if (d.password_manager === "bitwarden" && !keep) {
    say(`Bitwarden: create an "SSH key" item in the desktop app (vault → New → SSH key), then copy its public key.`);
  }
  const how = choose(`SSH key for ${what}`, opts, keep ? "keep" : opts[0].value);
  if (how === "keep") return current!;
  if (how === "skip") return "";
  if (how === "create") {
    const k = opCreateKey(i.vault, `${i.label} ${slugOf(h.host)} SSH key`);
    if (k) { say(`  Created. Public key: ${k}`); return k; }
    say("  Couldn't create it; paste one instead.");
  }
  return ask(`Public key for ${what}`, "", { placeholder: "ssh-ed25519 AAAA...", check: checkKey });
}

function askServices(i: Identity, advanced: boolean) {
  if (!advanced && !i.services.length && !confirm(`Set up API keys for ${i.label} now (Linear, Jira, Sentry, Stripe…)? You can add them later by running the wizard again.`, false)) return;
  i.services = chooseMany(
    `Which services should ${i.label} have API keys for?`,
    Object.entries(CATALOG).map(([value, s]) => ({ value, label: s.label })),
    i.services,
  );
  while (advanced && confirm(`Add another secret for ${i.label} that isn't in that list?`, false)) {
    const name = ask("Environment variable name", "", { placeholder: "MY_API_KEY", check: (v) => (/^[A-Z_][A-Z0-9_]*$/.test(v) ? null : "Use UPPER_CASE letters, numbers and _") });
    const item = ask("Password manager item that holds it", "", { placeholder: "My Service" });
    const field = ask("Field inside that item", "credential");
    const env = confirm("Export it to the environment automatically? (No = only via `fnox get`)", true);
    (i.secrets ??= {})[name] = { item, field, ...(env ? {} : { env: false }) };
  }
}

function askKeyValues(question: string, current: Record<string, string> = {}): Record<string, string> {
  const out = { ...current };
  while (confirm(question, false)) {
    const k = ask("Name", "");
    out[k] = ask(`Value for ${k}`, out[k] ?? "", { optional: true });
  }
  return out;
}

function askHosts(i: Identity, advanced: boolean, githubOwnerQuestion: string) {
  const gh = i.hosts.find((h) => h.host === "github.com");
  const owner = ask(githubOwnerQuestion, gh?.owner ?? "", { placeholder: "acme-inc" });
  const rest = i.hosts.filter((h) => h.host !== "github.com");
  i.hosts = [{ ...(gh ?? { host: "github.com" }), owner }, ...rest];
  if (!advanced) return;
  i.hosts = [i.hosts[0], ...rest.filter((h) => confirm(`Keep ${h.host}/${h.owner}?`))];
  while (confirm(`Does ${i.label} also use another git host (Bitbucket, GitLab, self-hosted)?`, false)) {
    const host = choose("Which host?", [
      { value: "bitbucket.org", label: "Bitbucket (bitbucket.org)" },
      { value: "gitlab.com", label: "GitLab (gitlab.com)" },
      { value: "other", label: "Other (self-hosted)" },
    ]);
    const name = host === "other" ? ask("Hostname", "", { placeholder: "git.example.com" }) : host;
    const h: Host = { host: name, owner: ask(`Workspace / group / owner on ${name}`, "") };
    h.rewrite_https = confirm(`Turn https:// clone URLs for ${name}/${h.owner} into SSH automatically?`, true);
    i.hosts.push(h);
  }
}

async function askIdentity(d: Data, id: string, i: Identity, advanced: boolean, personal: boolean, editing = false) {
  title(personal ? "Your personal account" : `Work account: ${i.label}`);
  if (personal) {
    askHosts(i, advanced, "Your personal GitHub username");
    const noreply = await githubNoreply(i.hosts[0].owner);
    if (!noreply) say(`  Couldn't find github.com/${i.hosts[0].owner} (typo, or offline). Continuing without GitHub's private address.`);
    const useNoreply =
      noreply &&
      choose("Which email should your personal commits use?", [
        { value: "noreply", label: `GitHub's private address ${noreply} (keeps your real email out of public history)` },
        { value: "own", label: i.email && i.email !== noreply ? `Keep ${i.email}` : "Another email" },
      ], i.email === noreply || !i.email ? "noreply" : "own") === "noreply";
    i.email = useNoreply ? noreply! : ask("Email for your personal commits", i.email === noreply ? "" : i.email, { check: checkEmail });
  } else {
    if (editing) i.label = ask("Name of the organization (as you'd write it)", i.label, { placeholder: "Acme" });
    askHosts(i, advanced, `${i.label}'s GitHub organization (as in github.com/<org>)`);
    i.email = ask(`Your email at ${i.label}`, i.email, { check: checkEmail });
  }
  if (!personal) {
    const separate = choose(
      `Do you log in to GitHub with a separate account for ${i.label}?`,
      [
        { value: "own", label: `Yes, I have a separate GitHub account for ${i.label}` },
        { value: "personal", label: "No, I use my personal GitHub account" },
      ],
      i.gh_account === "personal" ? "personal" : "own",
    );
    i.gh_account = separate === "own" ? id : "personal";
  }
  if (advanced) {
    i.vault = ask(d.password_manager === "bitwarden" ? "Bitwarden item-name prefix for this identity" : "1Password vault for this identity", i.vault || i.label);
    i.env = askKeyValues(`Add a non-secret environment variable for ${i.label}? (e.g. AWS_PROFILE)`, i.env);
    i.tools = askKeyValues(`Pin a tool version for ${i.label}? (mise tool name, e.g. node or ruby)`, i.tools);
  } else {
    i.vault ||= i.label;
  }
  askServices(i, advanced);
}

function emptyIdentity(label: string): Identity {
  return { label, email: "", vault: label, gh_account: "personal", services: [], hosts: [] };
}

async function interactive(existing: Data | null): Promise<Data> {
  title("Multi-identity dotfiles setup");
  say(
    [
      `This sets up your computer so that each folder under ~/${existing?.root ?? "code"}/<account> automatically uses the right`,
      "git name, email, SSH key, GitHub login and API keys. Passwords and tokens stay in your password",
      "manager; only references to them are written to disk. You'll review everything before it's applied.",
    ].join("\n"),
  );

  const fresh = !existing || Object.values(existing.identities).some((i) => i.hosts.some((h) => isPlaceholder(h.key)) && ["org1", "org2"].includes(i.hosts[0]?.owner));
  const d: Data = fresh
    ? { name: "", root: "code", password_manager: "1password", identities: { personal: { ...emptyIdentity("Personal"), gh_account: "personal" } } }
    : structuredClone(existing!);
  if (!fresh) {
    say("Found your current setup; answers default to what's there.");
    const what = choose("What do you want to do?", [
      { value: "all", label: "Review or change everything (accounts, emails, API keys, SSH keys)" },
      { value: "add", label: "Add a work account" },
      { value: "keys", label: "Only SSH keys (add, replace or create)" },
      { value: "steps", label: "Show the next-steps checklist again" },
    ], "all");
    if (what === "steps") { nextSteps(d); process.exit(0); }
    if (what === "keys") { askKeys(d); return d; }
    if (what === "add") { await addAccounts(d, flag("--advanced")); askKeys(d); return d; }
  }

  const advanced = flag("--advanced") || choose("How much do you want to configure?", [
    { value: "beginner", label: "Beginner: just the essentials, sensible defaults for the rest" },
    { value: "advanced", label: "Advanced: hosts, folders, services, env vars, tool versions" },
  ], "beginner") === "advanced";

  d.password_manager = choose("Which password manager do you use?", [
    { value: "1password", label: "1Password" },
    { value: "bitwarden", label: "Bitwarden" },
  ], d.password_manager);
  checkPrereqs(d.password_manager);

  title("About you");
  d.name = ask("Your name, as it should appear on commits", d.name || gitUserName());
  if (advanced) d.root = ask("Folder (inside your home) where your projects live", d.root, { check: (v) => (v.startsWith("/") || v.includes("..") ? "Use a path inside your home, like code or work/projects" : null) });

  await askIdentity(d, "personal", (d.identities.personal ??= emptyIdentity("Personal")), advanced, true);

  // Work accounts: keep / edit / remove the existing ones, then add new ones.
  for (const [id, i] of Object.entries(d.identities)) {
    if (id === "personal") continue;
    const what = choose(`Work account "${i.label}"`, [
      { value: "keep", label: "Keep as is" },
      { value: "edit", label: "Edit" },
      { value: "remove", label: "Remove" },
    ], "keep");
    if (what === "remove") delete d.identities[id];
    if (what === "edit") await askIdentity(d, id, i, advanced, false, true);
  }
  await addAccounts(d, advanced);
  askKeys(d);
  return d;
}

async function addAccounts(d: Data, advanced: boolean) {
  while (confirm(Object.keys(d.identities).length > 1 ? "Add another work account?" : "Add a work account (an organization you commit for)?", Object.keys(d.identities).length === 1)) {
    const label = ask("Name of the organization", "", { placeholder: "Acme" });
    let id = toId(label);
    if (!ID_RE.test(id)) id = ask("Short name for its folder (lowercase letters, numbers, -)", "", { check: checkId });
    while (d.identities[id]) id = ask(`A folder called "${id}" already exists; pick another short name`, `${id}-2`, { check: checkId });
    say(`  Its projects will live in ~/${d.root}/${id}`);
    const i = emptyIdentity(label);
    d.identities[id] = i;
    await askIdentity(d, id, i, advanced, false);
  }
}

function askKeys(d: Data) {
  title("SSH keys");
  say("One key per account. It lets this computer push to GitHub (or Bitbucket/GitLab) and sign your commits.\nThe private half never leaves your password manager; only the public half is written to disk.");
  for (const i of Object.values(d.identities)) {
    i.hosts.forEach((h, n) => {
      if (n > 0 && !confirm(`Use a separate key for ${i.label} on ${h.host}?`, !!h.key && h.key !== i.hosts[0].key)) { h.key = ""; return; }
      h.key = askKey(d, i, h, h.key);
    });
  }
}

function summary(d: Data) {
  title("Summary");
  const rows = Object.entries(d.identities).map(([id, i]) => [
    `~/${d.root}/${id}`,
    i.email,
    i.hosts.map((h) => `${h.host}/${h.owner}${h.key ? "" : " (no key)"}`).join(", "),
    `gh: ${i.gh_account}`,
    i.services.length + Object.keys(i.secrets ?? {}).length ? [...i.services, ...Object.keys(i.secrets ?? {})].join(", ") : "-",
  ]);
  if (useGum) {
    const csv = [["Folder", "Email", "Git hosts", "GitHub login", "Secrets"], ...rows].map((r) => r.map((c) => `"${c.replace(/"/g, '""')}"`).join(",")).join("\n");
    Bun.spawnSync(["gum", "table", "--print", "--separator", ","], { stdin: Buffer.from(csv), stdout: "inherit", stderr: "inherit" });
  } else {
    for (const r of rows) console.log(`  ${r.join("  |  ")}`);
  }
  say(`Name: ${d.name} · password manager: ${d.password_manager}`);
}

function nextSteps(d: Data) {
  title("Next steps");
  const steps: string[] = [];
  const keys = Object.values(d.identities).flatMap((i) =>
    i.hosts.filter((h, n) => h.key && (n === 0 || h.key !== i.hosts[0].key)).map((h) => `       ${i.label} on ${h.host}, signed in as that account:\n       ${h.key}`),
  );
  if (keys.length) {
    steps.push(
      "Add each public key to its account, TWICE: once as an Authentication key and once as a Signing key.\n" +
        "     GitHub: https://github.com/settings/keys · Bitbucket: Personal settings → SSH keys · GitLab: Preferences → SSH Keys\n" +
        keys.join("\n\n"),
    );
  }
  for (const acct of new Set(Object.values(d.identities).map((i) => i.gh_account))) {
    const cmd = isWindows
      ? `$env:GH_CONFIG_DIR="$HOME\\.config\\gh-${acct}"; gh auth login; Remove-Item Env:GH_CONFIG_DIR`
      : `GH_CONFIG_DIR=~/.config/gh-${acct} gh auth login`;
    steps.push(`Log in to the GitHub CLI as your "${acct}" account: ${cmd}`);
  }
  const items = Object.entries(d.identities).flatMap(([, i]) => [
    ...i.services.flatMap((s) => CATALOG[s].vars.map((v) => `${i.vault} → "${CATALOG[s].item}" → field "${v.field}"   (${v.name})`)),
    ...Object.entries(i.secrets ?? {}).map(([k, s]) => `${i.vault} → "${s.item}" → field "${s.field}"   (${k})`),
  ]);
  if (items.length) {
    const where = d.password_manager === "bitwarden" ? 'Bitwarden items named "<prefix> <item>" with a custom field' : "1Password items (vault → item → field)";
    steps.push(`Store your API keys in ${where}:\n${items.map((x) => `       ${x}`).join("\n")}`);
  }
  steps.push("Open a new terminal, then run: secrets-sync   (copies those API keys into each folder's encrypted local cache)");
  steps.push(`Try it: clone (or git init) a repo inside ~/${d.root}/personal, then run git config user.email in it`);
  steps.push(`Back up your answers so a new computer can reuse them: git -C "${REPO}" push`);
  steps.forEach((s, n) => console.log(`  ${n + 1}. ${s}`));
  say("Run this list again any time: mise run setup -- --next-steps");
}

function chezmoiApply() {
  const src = run(["chezmoi", "source-path"], { quiet: true });
  const sourceArgs = src.ok && src.out === REPO ? [] : ["--source", REPO];
  if (sourceArgs.length) say(`Note: chezmoi's default source is ${src.out || "(not set)"}; using this folder (${REPO}) instead.`);
  title("What will change in your home folder");
  say("A = add, M = modify, D = delete, R = run a one-time script");
  const st = run(["chezmoi", ...sourceArgs, "status"], { quiet: true });
  console.log(st.out || "(nothing to change)");
  // Second column M = an existing file of yours would be overwritten: back those up first.
  const overwritten = st.out.split("\n").filter((l) => l[1] === "M").map((l) => join(homedir(), l.slice(3)));
  if (overwritten.length) say(`Existing files that will be replaced get a backup copy first (<file>.bak-<date>). Your own additions can then go in ~/.zshrc.local, ~/.gitconfig.local or ~/.ssh/config.local.`);
  if (flag("--no-apply")) return say("Stopping before apply (--no-apply). Run `chezmoi apply` when ready.");
  if (!flag("--yes") && !confirm("Apply these changes now?")) {
    return say("Not applied. Run `chezmoi diff` to inspect and `chezmoi apply` when ready.");
  }
  const stamp = new Date().toISOString().slice(0, 19).replace(/[-:T]/g, "");
  for (const f of overwritten) if (existsSync(f) && statSync(f).isFile()) copyFileSync(f, `${f}.bak-${stamp}`);
  if (!run(["chezmoi", ...sourceArgs, "apply"]).ok) abort("chezmoi apply failed; see the message above.");
  say(overwritten.length ? `Applied. Backups: ${overwritten.map((f) => `${f}.bak-${stamp}`).join(", ")}` : "Applied.");
}

function offerCommit() {
  if (!existsSync(join(REPO, ".git"))) return;
  const st = run(["git", "-C", REPO, "status", "--porcelain"], { quiet: true });
  if (!st.ok || !st.out || (!process.stdin.isTTY && !flag("--yes"))) return;
  if (flag("--yes") || confirm("Commit these changes to your dotfiles repo? (not pushed)", true)) {
    run(["git", "-C", REPO, "add", "-A"], { quiet: true });
    run(["git", "-C", REPO, "commit", "-q", "-m", "setup: update identities"]);
  }
}

