async function main() {
  if (flag("--help") || flag("-h")) {
    console.log(readFileSync(import.meta.path, "utf8").split("\n").slice(1, 12).map((l) => l.replace(/^\/\/ ?/, "")).join("\n"));
    return;
  }
  if (flag("--next-steps")) return nextSteps(readData());
  const answers = flagValue("--answers");
  let d: Data;
  if (answers) {
    d = readData(answers);
  } else if (flag("--sync")) {
    d = readData();
  } else {
    if (!process.stdin.isTTY) abort("The wizard is interactive; use --answers FILE or --sync when there's no terminal.");
    d = await interactive(existsSync(USER_TOML) ? readData() : null);
  }

  const errs = validate(d);
  if (errs.length) abort(`Can't continue:\n${errs.map((e) => `  - ${e}`).join("\n")}`);

  if (!answers && !flag("--sync")) {
    summary(d);
    if (!confirm("Write this setup?")) abort();
  }
  if (!flag("--sync")) writeData(d); // --sync keeps a hand-edited user.toml (and its comments) untouched
  syncStubs(d);
  ensureAgeKey();
  chezmoiApply();
  offerCommit();
  if (!flag("--sync")) nextSteps(d);
}

await main();
