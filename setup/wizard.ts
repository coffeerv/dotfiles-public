#!/usr/bin/env bun
// Setup wizard. Asks a few questions, writes .chezmoidata/user.toml plus the small per-identity
// stub files chezmoi needs, then shows what will change and applies it.
//
//   mise run setup                    interactive (beginner by default, advanced on request)
//   mise run setup -- --advanced      start in advanced mode
//   mise run setup -- --answers FILE  non-interactive: FILE has the same format as .chezmoidata/user.toml
//   mise run setup -- --sync          only regenerate the stub files from the current user.toml
//   mise run setup -- --next-steps    print the after-setup checklist again
//   add --yes to apply without asking, --no-apply to stop before chezmoi apply,
//   --plain for simple line-by-line prompts (screen readers, dumb terminals; same as NO_GUM=1)
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, readSync, rmdirSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, relative, sep } from "node:path";

type Host = { host: string; owner: string; key?: string; rewrite_https?: boolean };
type Secret = { item: string; field: string; env?: boolean };
type Identity = {
  label: string;
  email: string;
  vault: string;
  gh_account: string;
  services: string[];
  hosts: Host[];
  env?: Record<string, string>;
  tools?: Record<string, string>;
  secrets?: Record<string, Secret>;
};
type Data = { name: string; root: string; password_manager: "1password" | "bitwarden"; identities: Record<string, Identity> };
type Service = { label: string; item: string; vars: { name: string; field: string }[]; env?: Record<string, string> };

const REPO = join(import.meta.dir, "..");
const USER_TOML = join(REPO, ".chezmoidata", "user.toml");
const CATALOG: Record<string, Service> = Bun.TOML.parse(readFileSync(join(REPO, ".chezmoidata", "services.toml"), "utf8")).services as any;
const STUB_MARK = "generated by setup";
const ID_RE = /^[a-z0-9][a-z0-9_-]*$/;

const argv = process.argv.slice(2);
const flag = (f: string) => argv.includes(f);
const flagValue = (f: string) => (argv.includes(f) ? argv[argv.indexOf(f) + 1] : undefined);

// ---------------------------------------------------------------------------------------------
// UI: gum when available (pretty menus), plain prompts otherwise. Same questions either way.

const useGum = !process.env.NO_GUM && !flag("--plain") && process.env.TERM !== "dumb" && !!Bun.which("gum") && process.stdin.isTTY;
const isWindows = process.platform === "win32";

function abort(msg = "Setup cancelled. Your home folder wasn't changed. (SSH keys already created in your password manager stay there; running the wizard again reuses them.)"): never {
  console.error(`\n${msg}`);
  process.exit(1);
}

function gum(args: string[]) {
  const p = Bun.spawnSync(["gum", ...args], { stdin: "inherit", stdout: "pipe", stderr: "inherit" });
  if (p.exitCode === 130) abort();
  return { ok: p.exitCode === 0, out: p.stdout.toString().replace(/\r?\n$/, "") };
}

// Not Bun's prompt(): it returns null for an empty line too, so Enter-for-default would look like EOF.
function line(question: string): string {
  process.stdout.write(question);
  const bytes: number[] = [];
  const b = Buffer.alloc(1);
  for (;;) {
    let n: number;
    try {
      n = readSync(0, b, 0, 1, null);
    } catch (e: any) {
      if (e.code === "EAGAIN") continue;
      throw e;
    }
    if (n === 0) { if (!bytes.length) abort(); break; }
    if (b[0] === 0x0a) break;
    bytes.push(b[0]);
  }
  return Buffer.from(bytes).toString("utf8").replace(/\r$/, "").trim();
}

function title(text: string) {
  console.log(useGum ? gum(["style", "--bold", "--margin", "1 0 0 0", text]).out : `\n== ${text} ==`);
}

function say(text: string) {
  console.log(text);
}

function ask(question: string, def = "", opts: { placeholder?: string; optional?: boolean; check?: (v: string) => string | null } = {}): string {
  for (;;) {
    let v: string;
    if (useGum) {
      const args = ["input", "--header", question, "--value", def, "--width", "0"];
      if (opts.placeholder) args.push("--placeholder", opts.placeholder);
      v = gum(args).out.trim();
    } else {
      v = line(`${question}${def ? ` [${def}]` : ""}: `) || def;
    }
    if (!v && !opts.optional) { say("  Error: this one is required."); continue; }
    const err = v && opts.check ? opts.check(v) : null;
    if (err) { say(`  Error: ${err}`); continue; }
    return v;
  }
}

function choose<T extends string>(question: string, options: { value: T; label: string }[], def?: T): T {
  if (useGum) {
    const args = ["choose", "--header", question];
    const d = options.find((o) => o.value === def);
    if (d) args.push("--selected", d.label);
    const out = gum([...args, ...options.map((o) => o.label)]).out;
    const hit = options.find((o) => o.label === out);
    if (!hit) abort();
    return hit.value;
  }
  console.log(question);
  options.forEach((o, n) => console.log(`  ${n + 1}) ${o.label}${o.value === def ? "  (default)" : ""}`));
  for (;;) {
    const a = line("> ");
    if (!a && def) return def;
    const n = Number(a);
    if (n >= 1 && n <= options.length) return options[n - 1].value;
    say(`  Not an option: ${a}. Type a number from 1 to ${options.length}.`);
  }
}

function chooseMany(question: string, options: { value: string; label: string }[], selected: string[]): string[] {
  if (useGum) {
    const args = ["choose", "--no-limit", "--header", `${question} (space to toggle, enter to confirm)`];
    const sel = options.filter((o) => selected.includes(o.value)).map((o) => o.label);
    if (sel.length) args.push("--selected", sel.join(","));
    const out = gum([...args, ...options.map((o) => o.label)]).out;
    return options.filter((o) => out.split("\n").includes(o.label)).map((o) => o.value);
  }
  console.log(`${question} (numbers separated by commas; Enter = keep current, - = none)`);
  options.forEach((o, n) => console.log(`  ${n + 1}) ${o.label}${selected.includes(o.value) ? "  (selected)" : ""}`));
  for (;;) {
    const a = line("> ");
    if (!a) return selected;
    if (a === "-") return [];
    const parts = a.split(",").map((x) => x.trim());
    const bad = parts.filter((x) => !(Number(x) >= 1 && Number(x) <= options.length));
    if (bad.length) { say(`  Not an option: ${bad.join(", ")}. Use numbers from 1 to ${options.length}.`); continue; }
    return [...new Set(parts.map((x) => options[Number(x) - 1].value))];
  }
}

function confirm(question: string, def = true): boolean {
  if (useGum) {
    const p = Bun.spawnSync(["gum", "confirm", `--default=${def}`, question], { stdin: "inherit", stdout: "inherit", stderr: "inherit" });
    if (p.exitCode === 130) abort();
    return p.exitCode === 0;
  }
  const a = line(`${question} [${def ? "Y/n" : "y/N"}] `).toLowerCase();
  return a ? a.startsWith("y") || a.startsWith("s") : def;
}

