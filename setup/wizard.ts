// Helpers

function run(cmd: string[], opts: { quiet?: boolean; cwd?: string } = {}) {
  const p = Bun.spawnSync(cmd, { cwd: opts.cwd, stdin: "inherit", stdout: opts.quiet ? "pipe" : "inherit", stderr: opts.quiet ? "pipe" : "inherit" });
  return { ok: p.exitCode === 0, out: p.stdout?.toString().trim() ?? "", err: p.stderr?.toString().trim() ?? "" };
}

const has = (bin: string) => !!Bun.which(bin);
const slugOf = (host: string) => host.split(".")[0];
const toId = (label: string) => label.toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const isPlaceholder = (key?: string) => !key || key.includes("REPLACE_WITH");
const checkEmail = (v: string) => (/^[^\s@]+@[^\s@]+$/.test(v) ? null : "That doesn't look like an email address.");
const checkKey = (v: string) => (/^(ssh-ed25519|ssh-rsa|ecdsa-sha2-\S+|sk-\S+) [A-Za-z0-9+/=]+/.test(v) ? null : "Paste the PUBLIC key: one line starting with ssh-ed25519 (or ssh-rsa).");
const checkId = (v: string) => (ID_RE.test(v) ? null : "Use lowercase letters, numbers, - or _ (it becomes a folder name).");

function gitUserName() {
  const r = run(["git", "config", "--global", "user.name"], { quiet: true });
  return r.ok ? r.out : "";
}

async function githubNoreply(user: string): Promise<string | null> {
  try {
    const r = await fetch(`https://api.github.com/users/${encodeURIComponent(user)}`, { signal: AbortSignal.timeout(5000) });
    if (!r.ok) return null;
    const j: any = await r.json();
    return j?.id ? `${j.id}+${j.login}@users.noreply.github.com` : null;
  } catch {
    return null;
  }
}

