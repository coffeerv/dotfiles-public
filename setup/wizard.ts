// user.toml: read and write (fixed schema, so a small writer is enough)

function readData(file = USER_TOML): Data {
  const d = Bun.TOML.parse(readFileSync(file, "utf8")) as any;
  return d as Data;
}

const tomlKey = (k: string) => (/^[A-Za-z0-9_-]+$/.test(k) ? k : JSON.stringify(k));
const tomlVal = (v: unknown): string =>
  typeof v === "string" ? JSON.stringify(v) : Array.isArray(v) ? `[${v.map(tomlVal).join(", ")}]` : String(v);

function writeData(d: Data) {
  const out: string[] = [
    "# Your setup. Written by the wizard (`mise run setup`); safe to edit by hand, then run",
    "# `mise run setup -- --sync` to regenerate the per-identity files. Public data only:",
    "# names, emails and PUBLIC keys. Private keys and tokens stay in your password manager.",
    "",
    `name = ${tomlVal(d.name)}`,
    `root = ${tomlVal(d.root)}`,
    `password_manager = ${tomlVal(d.password_manager)}`,
  ];
  for (const [id, i] of Object.entries(d.identities)) {
    out.push("", `[identities.${tomlKey(id)}]`);
    for (const k of ["label", "email", "vault", "gh_account", "services"] as const) out.push(`${k} = ${tomlVal(i[k])}`);
    for (const h of i.hosts) {
      out.push("", `[[identities.${tomlKey(id)}.hosts]]`, `host = ${tomlVal(h.host)}`, `owner = ${tomlVal(h.owner)}`, `key = ${tomlVal(h.key ?? "")}`);
      if (h.rewrite_https) out.push("rewrite_https = true");
    }
    for (const section of ["env", "tools"] as const) {
      const t = i[section];
      if (t && Object.keys(t).length) {
        out.push("", `[identities.${tomlKey(id)}.${section}]`);
        for (const [k, v] of Object.entries(t)) out.push(`${tomlKey(k)} = ${tomlVal(v)}`);
      }
    }
    for (const [name, s] of Object.entries(i.secrets ?? {})) {
      out.push("", `[identities.${tomlKey(id)}.secrets.${tomlKey(name)}]`, `item = ${tomlVal(s.item)}`, `field = ${tomlVal(s.field)}`);
      if (s.env === false) out.push("env = false");
    }
  }
  writeFileSync(USER_TOML, out.join("\n") + "\n");
}

function validate(d: Data): string[] {
  const errs: string[] = [];
  if (!d.name) errs.push("name is empty");
  if (!d.root || d.root.startsWith("/") || d.root.split(/[\\/]/).includes("..")) errs.push("root must be a folder inside your home, e.g. \"code\"");
  if (!["1password", "bitwarden"].includes(d.password_manager)) errs.push('password_manager must be "1password" or "bitwarden"');
  if (!d.identities || !Object.keys(d.identities).length) errs.push("at least one identity is needed");
  for (const [id, i] of Object.entries(d.identities ?? {})) {
    if (!ID_RE.test(id)) errs.push(`identity id "${id}": use lowercase letters, numbers, - or _`);
    if (!i.email || checkEmail(i.email)) errs.push(`${id}: email is missing or invalid`);
    if (!i.vault) errs.push(`${id}: vault is empty`);
    if (!i.gh_account || !ID_RE.test(i.gh_account)) errs.push(`${id}: gh_account must be a simple name`);
    if (!i.hosts?.length) errs.push(`${id}: needs at least one host`);
    for (const h of i.hosts ?? []) if (!h.host || !h.owner) errs.push(`${id}: every host needs host and owner`);
    const slugs = (i.hosts ?? []).map((h) => slugOf(h.host));
    if (new Set(slugs).size !== slugs.length) errs.push(`${id}: two hosts share the name "${slugs.find((s, n) => slugs.indexOf(s) !== n)}"`);
    for (const s of i.services ?? []) if (!CATALOG[s]) errs.push(`${id}: unknown service "${s}" (see .chezmoidata/services.toml)`);
    for (const [k, s] of Object.entries(i.secrets ?? {})) if (!s.item || !s.field) errs.push(`${id}: secret ${k} needs item and field`);
  }
  return errs;
}

// ---------------------------------------------------------------------------------------------
// Stub files: chezmoi can't create files whose NAMES come from data, so each identity gets a few
// one-line source files that call the shared templates in .chezmoitemplates/.

const sourcePath = (p: string) => p.split("/").map((c) => (c.startsWith(".") ? `dot_${c.slice(1)}` : c)).join("/");
const stub = (tpl: string, args: Record<string, string>) =>
  `{{- /* ${STUB_MARK}; edit .chezmoidata/user.toml instead */ -}}\n{{ template "${tpl}" (dict "root" .${Object.entries(args).map(([k, v]) => ` "${k}" "${v}"`).join("")}) }}\n`;

function expectedStubs(d: Data): Map<string, string> {
  const m = new Map<string, string>();
  for (const [id, i] of Object.entries(d.identities)) {
    m.set(`dot_gitconfig-${id}.tmpl`, stub("identity-gitconfig", { id }));
    m.set(`private_dot_ssh/id_${id}.pub.tmpl`, stub("pubkey", { id, slug: "" }));
    m.set(`${sourcePath(d.root)}/${id}/fnox.toml.tmpl`, stub("identity-fnox", { id }));
    m.set(`${sourcePath(d.root)}/${id}/mise.toml.tmpl`, stub("identity-mise", { id }));
    i.hosts.forEach((h, n) => {
      if (n > 0 && h.key && h.key !== i.hosts[0].key) {
        const slug = slugOf(h.host);
        m.set(`dot_gitconfig-${id}-${slug}.tmpl`, stub("host-gitconfig", { id, slug }));
        m.set(`private_dot_ssh/id_${id}_${slug}.pub.tmpl`, stub("pubkey", { id, slug }));
      }
    });
  }
  return m;
}

function walk(dir: string, acc: string[] = []): string[] {
  for (const e of readdirSync(dir)) {
    if ([".git", "node_modules", "setup"].includes(e)) continue;
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, acc);
    else if (e.endsWith(".tmpl")) acc.push(p);
  }
  return acc;
}

function syncStubs(d: Data) {
  const want = expectedStubs(d);
  let added = 0, removed = 0;
  for (const [rel, content] of want) {
    const p = join(REPO, rel);
    if (existsSync(p) && readFileSync(p, "utf8").replace(/\r\n/g, "\n") === content) continue; // CRLF checkouts on Windows count as equal
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
    added++;
  }
  for (const p of walk(REPO)) {
    const rel = relative(REPO, p).split(sep).join("/");
    if (want.has(rel) || !readFileSync(p, "utf8").includes(STUB_MARK)) continue;
    unlinkSync(p);
    removed++;
    for (let dir = dirname(p); dir !== REPO && readdirSync(dir).length === 0; dir = dirname(dir)) rmdirSync(dir);
  }
  say(`Per-identity files: ${added} written, ${removed} removed.`);
}

